void TestImageIo::exifOrientationAppliedOnLoad()
{
    QTemporaryDir dir;
    const QString path = dir.filePath("oriented.jpg");
    QFile file(path);
    QVERIFY(file.open(QIODevice::WriteOnly));
    file.write(reinterpret_cast<const char *>(kExifRotated90Jpeg),
               sizeof(kExifRotated90Jpeg));
    file.close();

    // Raw pixels are 4x2; Orientation=6 must rotate them to 2x4 on load,
    // moving the black left half to the top rows.
    QImage loaded;
    QVERIFY(ImageIo::load(path, &loaded));
    QCOMPARE(loaded.size(), QSize(2, 4));
    QVERIFY(loaded.pixelColor(1, 0).lightness() < 128);
    QVERIFY(loaded.pixelColor(0, 3).lightness() > 128);

    // The in-memory path honors the same metadata.
    QImage fromData;
    QVERIFY(ImageIo::loadData(
        QByteArray(reinterpret_cast<const char *>(kExifRotated90Jpeg),
                   sizeof(kExifRotated90Jpeg)),
        &fromData));
    QCOMPARE(fromData, loaded);
}

void TestImageIo::loadDataDecodesPngBytes()
{
    QImage original(8, 6, QImage::Format_ARGB32_Premultiplied);
    original.fill(Qt::white);
    original.setPixelColor(3, 4, QColor(200, 100, 50));

    QByteArray bytes;
    QBuffer buffer(&bytes);
    buffer.open(QIODevice::WriteOnly);
    QVERIFY(original.save(&buffer, "png"));

    QImage loaded;
    QVERIFY(ImageIo::loadData(bytes, &loaded));
    QCOMPARE(loaded, original);
}

void TestImageIo::loadDataRejectsGarbage()
{
    QImage loaded;
    QString error;
    QVERIFY(!ImageIo::loadData(QByteArrayLiteral("not an image"), &loaded, &error));
    QVERIFY(!error.isEmpty());
    QVERIFY(!ImageIo::loadData(QByteArray(), &loaded));
}

void TestImageIo::loadMissingFileFails()
{
    QImage out;
    QString error;
    QVERIFY(!ImageIo::load("/nonexistent/nowhere.png", &out, &error));
    QVERIFY(!error.isEmpty());
}

void TestImageIo::loadInvalidFileFails()
{
    QTemporaryDir dir;
    const QString path = dir.filePath("garbage.png");
    QFile file(path);
    QVERIFY(file.open(QIODevice::WriteOnly));
    file.write("this is not an image");
    file.close();

    QImage out;
    QString error;
    QVERIFY(!ImageIo::load(path, &out, &error));
    QVERIFY(!error.isEmpty());
}

void TestImageIo::saveToBadPathFails()
{
    QImage image(4, 4, QImage::Format_ARGB32_Premultiplied);
    image.fill(Qt::white);

    QString error;
    QVERIFY(!ImageIo::save("/nonexistent/dir/out.png", image, &error));
    QVERIFY(!error.isEmpty());
}

void TestImageIo::tinyImageRoundTrip()
{
    QTemporaryDir dir;
    const QString path = dir.filePath("tiny.png");

    QImage original(1, 1, QImage::Format_ARGB32_Premultiplied);
    original.setPixelColor(0, 0, QColor(1, 2, 3));

    QVERIFY(ImageIo::save(path, original));

    QImage loaded;
    QVERIFY(ImageIo::load(path, &loaded));
    QCOMPARE(loaded, original);
}

